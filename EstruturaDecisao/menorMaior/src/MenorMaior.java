public class MenorMaior {
    public static void main(String[] args) {
        
        int x = 1;
        int y = 85;

        if (x > y) {
            int calculo = x - y;
            System.out.println(calculo);
        }else{
            int calculo = y - x;
            System.out.println(calculo);
        }
    }
}
